// newAuthSrv 为 config 向导构造独立的认证通道 client。
func newAuthSrv(ctx context.Context) *rest.Client {
	return rest.NewClient(fshttp.NewClient(ctx)).SetRoot(api.TokenBaseURL)
}

// wizardSessions 保存向导两次状态调用之间的授权会话（uuid 与授权页
// 地址），按 remote 名隔离。uuid 是授权环第二步 preAuth 的必备参数，
// 不能落盘（它属于一次性会话）。
var wizardSessions sync.Map

type wizardSession struct {
	uuid        string
	authPageURL string
}

// Config is the state machine for `rclone config`：
// 生成/复用 clawUid → preAuth（不带 uuid）→ 展示 authPageUrl →
// 用户浏览器完成授权后按回车 → preAuth（带 uuid）→ 103000 →
// access_token 与 claw_uid 写入配置。
func Config(ctx context.Context, name string, m configmap.Mapper, conf fs.ConfigIn) (*fs.ConfigOut, error) {
	switch conf.State {
	case "":
		rawToken, _ := m.Get("access_token")
		clawUID, _ := m.Get("claw_uid")
		// 已有凭据时先静默验证，避免每次 config 都强制重授权
		if rawToken != "" && clawUID != "" {
			srv := newAuthSrv(ctx)
			auth := api.NewAuth(rawToken, clawUID, srv)
			result, err := auth.PreAuth(ctx, "")
			if err == nil && result.ResultCode == "103000" {
				if result.AccessToken != "" {
					m.Set("access_token", result.AccessToken)
				}
				return nil, nil
			}
			// 验证失败（token 失效或网络错误）：继续走重新授权流程，
			// 保留原 clawUID 以维持专属目录不变
			if err != nil {
				fs.Debugf(nil, "cmcloud: silent token check failed: %v", err)
			}
		}
		if clawUID == "" {
			clawUID = uuid.NewString()
			m.Set("claw_uid", clawUID)
		}
		// 重新授权时不携带旧 accessToken（SDK 在 103001 后同样清空它）
		srv := newAuthSrv(ctx)
		auth := api.NewAuth("", clawUID, srv)
		result, err := auth.PreAuth(ctx, "")
		if err != nil {
			return nil, fmt.Errorf("cmcloud: preAuth failed: %w", err)
		}
		switch result.ResultCode {
		case "103000":
			// 不应出现（无 accessToken 时服务端要求授权），防御性处理
			if result.AccessToken != "" {
				m.Set("access_token", result.AccessToken)
				return nil, nil
			}
			return nil, errors.New("cmcloud: preAuth returned success without access token")
		case "103001":
			if result.AuthPageURL == "" || result.UUID == "" {
				return nil, errors.New("cmcloud: preAuth response missing authPageUrl or uuid")
			}
			wizardSessions.Store(name, &wizardSession{uuid: result.UUID, authPageURL: result.AuthPageURL})
			return fs.ConfigInput("auth_wait", "config_auth_wait", authPrompt(result.AuthPageURL))
		default:
			return nil, fmt.Errorf("cmcloud: preAuth returned %s (%s)", result.ResultCode, result.Desc)
		}
	case "auth_wait":
		clawUID, _ := m.Get("claw_uid")
		if clawUID == "" {
			return nil, errors.New("cmcloud: claw_uid is missing - restart `rclone config`")
		}
		var session *wizardSession
		if v, ok := wizardSessions.Load(name); ok {
			session = v.(*wizardSession)
		}
		if session == nil || session.uuid == "" {
			return fs.ConfigError("", "authorization session lost - restart `rclone config`")
		}
		srv := newAuthSrv(ctx)
		auth := api.NewAuth("", clawUID, srv)
		result, err := auth.PreAuth(ctx, session.uuid)
		if err != nil {
			return fs.ConfigError("auth_wait", "preAuth failed: "+err.Error())
		}
		switch result.ResultCode {
		case "103000":
			wizardSessions.Delete(name)
			if result.AccessToken == "" {
				return fs.ConfigError("auth_wait", "preAuth success but no access token in response - restart `rclone config`")
			}
			m.Set("access_token", result.AccessToken)
			return nil, nil
		case "103001":
			// 会话被服务端作废，换新入口重试
			if result.AuthPageURL == "" || result.UUID == "" {
				return fs.ConfigError("auth_wait", "preAuth response missing authPageUrl or uuid")
			}
			wizardSessions.Store(name, &wizardSession{uuid: result.UUID, authPageURL: result.AuthPageURL})
			return fs.ConfigError("auth_wait", "The previous authorization session was invalidated. Open the new URL below, finish the authorization, then press Enter again.\n\n"+result.AuthPageURL)
		case "130088":
			// 会话未完成授权：重放同一入口（实测出现过用户自认已授权但
			// 服务端仍回 130088 的情况，须走到页面最终成功提示）
			return fs.ConfigError("auth_wait", "The authorization is not finished yet. Make sure the page opened from the URL below reaches its final success message, then press Enter again.\n\n"+session.authPageURL)
		default:
			return fs.ConfigError("auth_wait", fmt.Sprintf("preAuth returned %s (%s)", result.ResultCode, result.Desc))
		}
	}
	return nil, fmt.Errorf("cmcloud: unknown config state %q", conf.State)
}

// authPrompt 生成授权页提示文案。
func authPrompt(authPageURL string) string {
	return fmt.Sprintf(`Open the following URL in a browser, sign in with the China Mobile account that owns the files and approve the authorization:

%s

The authorization must reach the final success page (a page that only says "authorized" midway is not enough). Then return here and press Enter. If you are configuring rclone on a remote machine without a browser, forward the URL to a machine with one and complete it there.`, authPageURL)
}

// NewFs constructs an Fs from the path.
//
// root 一律是专属目录内的相对路径；专属目录 folderId 由 user/folder/query
// 查询获得并作为目录树的 trueRootID。
func NewFs(ctx context.Context, name, root string, m configmap.Mapper) (fs.Fs, error) {
	opt := new(Options)
	if err := configstruct.Set(m, opt); err != nil {
		return nil, err
	}
	if opt.AccessToken == "" || opt.ClawUID == "" {
		return nil, errors.New("cmcloud: access_token and claw_uid are required - run `rclone config` to set up this remote")
	}
	if opt.ChunkSize < minChunkSize {
		return nil, fmt.Errorf("cmcloud: chunk_size (%v) must be greater than or equal to %v", opt.ChunkSize, fs.SizeSuffix(minChunkSize))
	}
	if opt.UploadCutoff < 0 {
		return nil, errors.New("cmcloud: upload_cutoff must not be negative")
	}
	root = strings.Trim(root, "/")

	f := &Fs{
		name: name,
		root: root,
		opt:  *opt,
	}
	f.srvSetup(ctx)
	f.features = (&fs.Features{
		CaseInsensitive:         false,
		CanHaveEmptyDirectories: true,
	}).Fill(ctx, f)

	// 锚定专属目录
	folder, err := f.c.UserFolderQuery(ctx)
	if err != nil {
		return nil, fmt.Errorf("cmcloud: failed to query dedicated directory: %w", err)
	}
	f.dirCache = dircache.New(root, folder.FolderID, f)

	// root 路径不存在时按 rclone 约定处理：先假设它是一个文件，
	// 退到父目录验证；父目录也不存在则返回原 Fs（Mkdir 时再建）。
	err = f.dirCache.FindRoot(ctx, false)
	if err != nil {
		newRoot, remote := dircache.SplitPath(root)
		tempF := *f
		tempF.dirCache = dircache.New(newRoot, folder.FolderID, &tempF)
		tempF.root = newRoot
		err = tempF.dirCache.FindRoot(ctx, false)
		if err != nil {
			// root 不存在，返回原 Fs
			return f, nil
		}
		_, err = tempF.NewObject(ctx, remote)
		if err != nil {
			if errors.Is(err, fs.ErrorObjectNotFound) {
				// root 指向的名字不存在：当作普通根目录
				return f, nil
			}
			return nil, err
		}
		f.features.Fill(ctx, &tempF)
		f.dirCache = tempF.dirCache
		f.root = tempF.root
		// 返回指向父目录的 Fs + ErrorIsFile
		return f, fs.ErrorIsFile
	}
	return f, nil
}

// srvSetup 构造业务/认证 client 与 pacer。
func (f *Fs) srvSetup(ctx context.Context) {
	srv := rest.NewClient(fshttp.NewClient(ctx)).SetRoot(api.BusinessBaseURL)
	srv.SetErrorHandler(api.HTTPErrorHandler)
	authSrv := rest.NewClient(fshttp.NewClient(ctx)).SetRoot(api.TokenBaseURL)
	f.auth = api.NewAuth(f.opt.AccessToken, f.opt.ClawUID, authSrv)
	f.pacer = api.NewPacer(ctx)
	f.c = api.NewClient(srv, f.auth, f.pacer)
	f.client = fshttp.NewClient(ctx) // 预签名 PUT/GET 直传
}

