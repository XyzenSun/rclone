// FindLeaf finds a directory of name leaf in the folder with ID pathID
// (dircache.DirCacher 接口，leaf 为 rclone 标准名)。
func (f *Fs) FindLeaf(ctx context.Context, pathID, leaf string) (pathIDOut string, found bool, err error) {
	found, err = f.listAll(ctx, pathID, func(item *api.Item) bool {
		if item.IsFolder() && f.opt.Enc.ToStandardName(item.Name) == leaf {
			pathIDOut = item.FileID
			return true
		}
		return false
	})
	return pathIDOut, found, err
}

// CreateDir makes a directory with pathID as parent and name leaf
// (dircache.DirCacher 接口)。dircache 先查后建，不会对已存在目录
// 调用本方法（服务端对同名 createFolder 会静默改名为时间戳副本）。
func (f *Fs) CreateDir(ctx context.Context, pathID, leaf string) (newID string, err error) {
	res, err := f.c.CreateFolder(ctx, f.opt.Enc.FromStandardName(leaf), pathID)
	if err != nil {
		return "", err
	}
	return res.FileID, nil
}

// listAll 翻页列出 pathID 下的全部条目，对每个条目调用 fn；
// fn 返回 true 时提前退出（found=true）。
func (f *Fs) listAll(ctx context.Context, pathID string, fn func(item *api.Item) bool) (found bool, err error) {
	cursor := ""
	for {
		res, err := f.c.FileList(ctx, pathID, cursor)
		if err != nil {
			return false, err
		}
		for i := range res.Items {
			if fn(&res.Items[i]) {
				return true, nil
			}
		}
		// items 为空但 cursor 非空时仍需继续翻页（实测结论）
		cursor = res.NextPageCursor
		if cursor == "" {
			break
		}
	}
	return false, nil
}

// itemModTime 取条目的修改时间：优先 localUpdatedAt（上传时设置的
// 本地时间，是 ModTime 往返一致性的唯一载体），缺失时回退 updatedAt。
func itemModTime(item *api.Item) time.Time {
	for _, s := range []string{item.LocalUpdatedAt, item.UpdatedAt} {
		if s == "" {
			continue
		}
		if t, err := time.Parse(time.RFC3339, s); err == nil {
			return t
		}
	}
	return time.Time{}
}

// newObjectWithInfo 把服务端条目转换为 Object。
func (f *Fs) newObjectWithInfo(remote string, item *api.Item) *Object {
	o := &Object{
		fs:     f,
		remote: remote,
	}
	o.setMetaData(item)
	return o
}

// setMetaData sets the metadata from info
func (o *Object) setMetaData(item *api.Item) {
	o.hasMetaData = true
	o.id = item.FileID
	o.size = item.Size
	o.modTime = itemModTime(item)
	if item.ContentHashAlgorithm == "sha256" || item.ContentHashAlgorithm == "" {
		o.sha256 = item.ContentHash
	}
}

// readMetaDataForPath reads the metadata for the file at path.
// 服务端无按名查询接口，只能列出父目录找名。
func (f *Fs) readMetaDataForPath(ctx context.Context, remote string) (*api.Item, error) {
	leaf, directoryID, err := f.dirCache.FindPath(ctx, remote, false)
	if err != nil {
		if errors.Is(err, fs.ErrorDirNotFound) {
			return nil, fs.ErrorObjectNotFound
		}
		return nil, err
	}
	var item *api.Item
	_, err = f.listAll(ctx, directoryID, func(candidate *api.Item) bool {
		if !candidate.IsFolder() && f.opt.Enc.ToStandardName(candidate.Name) == leaf {
			item = candidate
			return true
		}
		return false
	})
	if err != nil {
		return nil, err
	}
	if item == nil {
		return nil, fs.ErrorObjectNotFound
	}
	return item, nil
}

// NewObject finds the Object at remote.  If it can't be found
// it returns the error fs.ErrorObjectNotFound.
func (f *Fs) NewObject(ctx context.Context, remote string) (fs.Object, error) {
	o := &Object{
		fs:     f,
		remote: remote,
	}
	err := o.readMetaData(ctx)
	if err != nil {
		return nil, err
	}
	return o, nil
}

// readMetaData gets the metadata if it hasn't already been fetched
func (o *Object) readMetaData(ctx context.Context) (err error) {
	if o.hasMetaData {
		return nil
	}
	item, err := o.fs.readMetaDataForPath(ctx, o.remote)
	if err != nil {
		return err
	}
	o.setMetaData(item)
	return nil
}

// List the objects and directories in dir into entries.
//
// dir should be "" to list the root, and should not have trailing slashes.
func (f *Fs) List(ctx context.Context, dir string) (entries fs.DirEntries, err error) {
	directoryID, err := f.dirCache.FindDir(ctx, dir, false)
	if err != nil {
		return nil, err
	}
	return f.listDir(ctx, dir, directoryID)
}

// listDir 翻页列出一个目录并组装 DirEntries，同时把子目录 ID
// 写入 dircache 供后续路径解析复用。
func (f *Fs) listDir(ctx context.Context, dir, directoryID string) (entries fs.DirEntries, err error) {
	cursor := ""
	for {
		res, err := f.c.FileList(ctx, directoryID, cursor)
		if err != nil {
			return nil, err
		}
		for i := range res.Items {
			item := &res.Items[i]
			remote := path.Join(dir, f.opt.Enc.ToStandardName(item.Name))
			if item.IsFolder() {
				f.dirCache.Put(remote, item.FileID)
				entries = append(entries, fs.NewDir(remote, itemModTime(item)).SetID(item.FileID))
			} else {
				entries = append(entries, f.newObjectWithInfo(remote, item))
			}
		}
		cursor = res.NextPageCursor
		if cursor == "" {
			break
		}
	}
	return entries, nil
}

// ListR lists the objects and directories of the Fs starting
// from dir recursively.
//
// 递归下钻：目录入队逐层展开，避免递归调用栈过深。
func (f *Fs) ListR(ctx context.Context, dir string, callback fs.ListRCallback) (err error) {
	lh := list.NewHelper(callback)
	type dirQueueItem struct {
		remote string
		id     string
	}
	directoryID, err := f.dirCache.FindDir(ctx, dir, false)
	if err != nil {
		return err
	}
	queue := []dirQueueItem{{remote: dir, id: directoryID}}
	for len(queue) > 0 {
		current := queue[0]
		queue = queue[1:]
		entries, err := f.listDir(ctx, current.remote, current.id)
		if err != nil {
			return err
		}
		for _, entry := range entries {
			if err = lh.Add(entry); err != nil {
				return err
			}
			if d, ok := entry.(fs.Directory); ok {
				queue = append(queue, dirQueueItem{remote: d.Remote(), id: d.ID()})
			}
		}
	}
	return lh.Flush()
}

// Mkdir creates the container if it doesn't exist.
//
// rclone 语义：Mkdir("") 是创建 Fs 根目录本身，必须幂等。
// dircache 的先查后建保证不会对已存在目录触发服务端 createFolder。
func (f *Fs) Mkdir(ctx context.Context, dir string) error {
	_, err := f.dirCache.FindDir(ctx, dir, true)
	return err
}

// Put the object
//
// Copy the reader in to the new object which is returned.
//
// The new object may have been created if an error is returned.
func (f *Fs) Put(ctx context.Context, in io.Reader, src fs.ObjectInfo, options ...fs.OpenOption) (fs.Object, error) {
	o := &Object{
		fs:     f,
		remote: src.Remote(),
	}
	return o, o.Update(ctx, in, src, options...)
}

// Copy src to this remote using server-side copy operations.
//
// batchCopy 只能把文件原名复制到目标目录，不支持改名：目标叶名与
// 源不同时返回 fs.ErrorCantCopy，让上层回退到上传复制。
// 目标已存在时服务端会静默加时间戳后缀（实测行为），必须提前拦截。
func (f *Fs) Copy(ctx context.Context, src fs.Object, remote string) (fs.Object, error) {
	srcObj, ok := src.(*Object)
	if !ok {
		fs.Debugf(src, "Can't copy - not same remote type")
		return nil, fs.ErrorCantCopy
	}
	if err := srcObj.readMetaData(ctx); err != nil {
		return nil, err
	}
	_, srcLeaf := dircache.SplitPath(srcObj.remote)
	_, dstLeaf := dircache.SplitPath(remote)
	if srcLeaf != dstLeaf {
		fs.Debugf(src, "Can't copy %q -> %q: platform can't copy to a different name", srcObj.remote, remote)
		return nil, fs.ErrorCantCopy
	}
	// 预检目标不存在（服务端复制同名冲突会静默改名，rclone 语义要求报错）
	if _, err := f.NewObject(ctx, remote); err == nil {
		return nil, fmt.Errorf("cmcloud: can't copy %q: destination exists and the platform can't overwrite files", remote)
	} else if !errors.Is(err, fs.ErrorObjectNotFound) {
		return nil, err
	}
	_, directoryID, err := f.dirCache.FindPath(ctx, remote, true)
	if err != nil {
		return nil, err
	}
	taskID, err := f.c.BatchCopy(ctx, []string{srcObj.id}, directoryID)
	if err != nil {
		return nil, err
	}
	if _, err = f.c.WaitForTask(ctx, taskID); err != nil {
		return nil, err
	}
	// 服务端复制后存在短暂可见性延迟，定位副本时重试几次
	var copied fs.Object
	for range copyLocateTries {
		copied, err = f.NewObject(ctx, remote)
		if err == nil {
			return copied, nil
		}
		if !errors.Is(err, fs.ErrorObjectNotFound) {
			return nil, fmt.Errorf("cmcloud: failed to locate copied file: %w", err)
		}
		if err = sleepContext(ctx, 500*time.Millisecond); err != nil {
			return nil, err
		}
	}
	return nil, fmt.Errorf("cmcloud: failed to locate copied file: %w", err)
}

// sleepContext 等待指定时长，可被 ctx 取消中断。
func sleepContext(ctx context.Context, d time.Duration) error {
	select {
	case <-ctx.Done():
		return ctx.Err()
	case <-time.After(d):
		return nil
	}
}

