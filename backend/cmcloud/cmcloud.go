// 上传分片约束（服务端硬性限制）：
// 非末片不得小于 5MiB，partNumber 1~10000 连续递增，单批不超过 100 片。
// 分片规划保证总片数不超过 100（片数超限时增大单片），因此 create 响应
// 直接携带全部分片地址，getUploadUrl 补取路径在本规划下不可达。
const (
	minChunkSize    = 5 * 1024 * 1024
	defaultCutoff   = 5 * 1024 * 1024
	defaultChunk    = 32 * 1024 * 1024
	copyLocateTries = 3 // 服务端复制后短暂可见性延迟的重试次数
)

func init() {
	fs.Register(&fs.RegInfo{
		Name:        "cmcloud",
		Description: "China Mobile Cloud (中国移动云盘)",
		NewFs:       NewFs,
		Config:      Config,
		Options: []fs.Option{{
			Name:      "access_token",
			Help:      "Long-term access token from the IDaaS authorization - set by the config wizard.",
			Hide:      fs.OptionHideBoth,
			Sensitive: true,
		}, {
			Name: "claw_uid",
			Help: `Device identity (clawUid) bound to the authorization.

Generated by the config wizard on first authorization and bound to
the access_token on the server side. Keep it unchanged to keep the
same dedicated directory.`,
			Hide: fs.OptionHideBoth,
		}, {
			Name:     "upload_cutoff",
			Help:     "Cutoff for switching to multipart upload (>= 5 MiB).",
			Default:  fs.SizeSuffix(defaultCutoff),
			Advanced: true,
		}, {
			Name:     "chunk_size",
			Help:     "Chunk size for multipart upload (>= 5 MiB).\n\nFiles larger than upload_cutoff are split into chunks of this size. The number of parts is capped at 100; larger files get proportionally larger parts.",
			Default:  fs.SizeSuffix(defaultChunk),
			Advanced: true,
		}, {
			Name:     config.ConfigEncoding,
			Help:     config.ConfigEncodingHelp,
			Advanced: true,
			// 平台禁止的文件名字符 \/:*?"<>| 由 EncodeWin/EncodeBackSlash 覆盖。
			// EncodeDot/EncodeSlash 必须保留：encoder 的 Standard 层会把全角
			// 点/斜杠解码回 ASCII，前者被 path.Join 清洗后会让 create 落在父
			// 目录上替换掉整个目录（baidupcs 交付时的实测事故），后者会分裂
			// 路径。前导空格会被服务端裁剪（fstests 实测），尾部空格与尾部
			// 点按往返一致性编码。
			Default: (encoder.EncodeWin | // :?*<>| 平台禁止的文件名字符
				encoder.EncodeBackSlash |
				encoder.EncodeDot |
				encoder.EncodeSlash |
				encoder.EncodeLeftSpace | // 服务端裁剪前导空格（fstests 实测）
				encoder.EncodeRightSpace |
				encoder.EncodeRightPeriod |
				encoder.EncodeCtl |
				encoder.EncodeDel |
				encoder.EncodeInvalidUtf8),
		}},
	})
}

// Options defines the configuration for this backend.
type Options struct {
	AccessToken  string               `config:"access_token"`
	ClawUID      string               `config:"claw_uid"`
	UploadCutoff fs.SizeSuffix        `config:"upload_cutoff"`
	ChunkSize    fs.SizeSuffix        `config:"chunk_size"`
	Enc          encoder.MultiEncoder `config:"encoding"`
}

// Fs represents a remote cmcloud dedicated directory.
type Fs struct {
	name     string             // name of this remote
	root     string             // root path within the dedicated directory
	opt      Options            // parsed options
	features *fs.Features       // optional features
	c        *api.Client        // business API client
	auth     *api.Auth          // ticket manager
	pacer    *fs.Pacer          // pacer for API calls
	client   *http.Client       // for presigned PUT/GET transfers
	dirCache *dircache.DirCache // path -> fileId cache
}

// Object describes a cmcloud object.
type Object struct {
	fs          *Fs       // what this object is part of
	remote      string    // remote path
	hasMetaData bool      // whether info below has been set
	id          string    // fileId of the object
	size        int64     // size of the object
	modTime     time.Time // modification time of the object
	sha256      string    // content hash from the server
}

// ------------------------------------------------------------

// Name of the remote (as passed into NewFs)
func (f *Fs) Name() string {
	return f.name
}

// Root of the remote (as passed into NewFs)
func (f *Fs) Root() string {
	return f.root
}

// String converts this Fs to a string
func (f *Fs) String() string {
	return fmt.Sprintf("cmcloud dedicated directory root '%s'", f.root)
}

// Features returns the optional features of this Fs
func (f *Fs) Features() *fs.Features {
	return f.features
}

// Precision return the precision of this Fs.
// 服务端时间为毫秒精度；ModTime 只读（update 端点被屏蔽）。
func (f *Fs) Precision() time.Duration {
	return time.Millisecond
}

// Hashes returns the supported hash sets.
// 云空间底座提供 sha256（真实凭据实测确认）。
func (f *Fs) Hashes() hash.Set {
	return hash.Set(hash.SHA256)
}

