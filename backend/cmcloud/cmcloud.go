// Open an object for read
//
// 链路：getDownloadUrl 取预签名 GET 地址 → 直接流式读（S3 预签名
// 天然支持 Range）。地址有效期 1 小时，取一次即用。
func (o *Object) Open(ctx context.Context, options ...fs.OpenOption) (in io.ReadCloser, err error) {
	if err = o.readMetaData(ctx); err != nil {
		return nil, err
	}
	if o.id == "" {
		return nil, errors.New("cmcloud: can't download - no fileId")
	}
	fs.FixRangeOption(options, o.size)
	// Range 起点越过文件末尾时直接返回空内容（对齐 local backend 行为）
	for _, option := range options {
		if ro, ok := option.(*fs.RangeOption); ok && ro.Start >= o.size {
			return io.NopCloser(strings.NewReader("")), nil
		}
	}
	dl, err := o.fs.c.GetDownloadURL(ctx, o.id)
	if err != nil {
		return nil, err
	}
	var resp *http.Response
	err = o.fs.pacer.Call(func() (bool, error) {
		req, err := http.NewRequestWithContext(ctx, http.MethodGet, dl.URL, nil)
		if err != nil {
			return false, err
		}
		fs.OpenOptionAddHTTPHeaders(req.Header, options)
		resp, err = o.fs.client.Do(req)
		if err != nil {
			return fserrors.ShouldRetry(err), err
		}
		if resp.StatusCode != http.StatusOK && resp.StatusCode != http.StatusPartialContent {
			statusCode := resp.StatusCode
			_ = resp.Body.Close()
			resp = nil
			// 403 通常是预签名地址过期，交上层重试整个 Open（重新取地址）
			return statusCode == http.StatusForbidden || statusCode == http.StatusTooManyRequests || statusCode >= 500,
				fmt.Errorf("cmcloud: download failed: HTTP status %d", statusCode)
		}
		return false, nil
	})
	if err != nil {
		return nil, err
	}
	return resp.Body, nil
}

